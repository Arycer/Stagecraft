local I,G=require('instanced'),require('gui')
local ns='convert_'..stage.run_id
local folder=I.CONFIG..'schematics/'..ns..'/'
local ok,failure=pcall(function()
  stage.step('convertir schematic a estructura desde Ficheros',function()
    stage.host('file.write',{path=folder..'dungeon.schem',base64=require('fixtures').sponge})
    stage.command('gamemode creative'); I.tp_to('minecraft:overworld',60,121,56); stage.fly(true)
    G.admin(); G.tab(2); stage.click_text('^'..ns..'$'); stage.click_text('^dungeon\\.schem$'); stage.click_text('^Convertir a \\.nbt$')
    stage.wait_text('^Convertido a '..ns..'/dungeon\\.nbt · 4×3×4')
    assert(stage.host('file.exists',{path=folder..'dungeon.nbt'}).exists,'no se creó nbt')
    assert(stage.host('file.exists',{path=folder..'dungeon.schem'}).exists,'desapareció schematic')
  end)
  stage.step('segunda conversión pide confirmar reemplazo',function()
    stage.click_text('^dungeon\\.schem$'); stage.click_text('^Convertir a \\.nbt$')
    stage.wait_text('Ya existe'); stage.click_text('^Confirmar$'); stage.wait_text('^Convertido a '..ns..'/dungeon\\.nbt')
  end)
  stage.step('menú contextual ofrece conversión',function()
    stage.click_text('^dungeon\\.schem$',{button=1}); stage.wait_text('^Convertir a \\.nbt$'); stage.key('escape'); stage.close()
  end)
  stage.step('la estructura convertida conserva el cofre',function()
    stage.command('setblock 60 120 60 minecraft:air'); stage.command('setblock 60 120 60 instanced:capture')
    stage.command('instanced capture 60 120 60 place schematics '..ns..'/dungeon.nbt')
    stage.expect_chat('Colocado schematics/'..ns..'/dungeon\\.nbt · 17 bloques',30); stage.wait(0.5)
    G.block('61 121 61','minecraft:chest')
  end)
end)
if not ok then pcall(G.dump) end
I.cleanup(function() stage.command('execute in minecraft:overworld run fill 60 120 60 66 124 66 minecraft:air'); I.delete_namespace(ns) end)
if not ok then error(failure,0) end
