local I,G=require('instanced'),require('gui')
local ok,failure=pcall(function()
  stage.step('colocar ancla y zona',function()
    stage.command('gamemode creative'); I.tp_to('minecraft:overworld',0.5,120,0.5); stage.fly(true)
    stage.command('setblock 3 120 0 minecraft:air'); stage.command('setblock 0 120 3 minecraft:air')
    stage.command('setblock 3 120 0 instanced:anchor[facing=north]'); stage.command('setblock 0 120 3 instanced:room_zone')
  end)
  stage.step('ancla: id sugerido y dirección',function()
    G.open('3 120 0'); stage.wait_text('^Las anclas con el mismo id')
    stage.click_text('^door$'); stage.click_text('^Este$'); stage.click_text('^Guardar cambios$')
    G.nbt('3 120 0','MarkerId','"door"'); G.block('3 120 0','instanced:anchor[facing=east]')
  end)
  stage.step('zona: tamaño y pool de la lista',function()
    G.open('0 120 3'); stage.wait_text('^Caja 8×6×8')
    local plus=stage.wait_text('^\\+$'); local row=stage.wait_text('^Tamaño$')
    stage.click(plus.cx,row.cy); stage.wait_text('^Caja 9×6×8')
    stage.click_text('^Lista…$'); stage.click_text('^demo:decor$')
    G.field('demo:decor'); stage.wait_text('^Se rellena con un template de demo:decor\\.$')
    stage.click_text('^Guardar cambios$'); G.nbt('0 120 3','Pool','"demo:decor"'); G.nbt('0 120 3','Size',[=[\[I; 9, 6, 8\]]=])
  end)
  stage.step('portal: dirección, color, nivel y salida en toda la superficie',function()
    stage.command('fill 0 120 -3 0 121 -3 minecraft:air')
    stage.command('fill 0 120 -3 0 121 -3 instanced:entrance_portal[facing=north]')
    G.open('0 120 -3'); stage.wait_text('^Portal de entrada$'); stage.wait_text([[^2 bloque\(s\) conectados]])
    stage.click_text('^Este$'); stage.click_text('^Elegir color…$'); stage.wait_text('^Elegir color$')
    stage.wait_text('^#[0-9A-F]{6}$'); stage.click_text('^Aceptar$')
    local hex
    for n,w in ipairs(G.fields()) do if w.value:match('^%x%x%x%x%x%x$') then hex=n end end
    stage.set_field(assert(hex,'sin campo de color'),'3DDC84')
    stage.click_text('^Lista…$'); stage.click_text('^demo:showcase$'); stage.click_text('^Usar mi posición$'); stage.click_text('^Guardar cambios$')
    for _,y in ipairs({120,121}) do
      local at='0 '..y..' -3'; G.block(at,'instanced:entrance_portal[facing=east]'); G.nbt(at,'Color',': 4054148'); G.nbt(at,'Level','"demo:showcase"')
    end
    G.nbt('0 121 -3','Exit.Dimension','"minecraft:overworld"')
  end)
end)
if not ok then pcall(G.dump) end
I.cleanup(function()
  stage.command('execute in minecraft:overworld run fill 0 120 -3 0 121 -3 minecraft:air')
  stage.command('execute in minecraft:overworld run setblock 3 120 0 minecraft:air')
  stage.command('execute in minecraft:overworld run setblock 0 120 3 minecraft:air')
end)
if not ok then error(failure,0) end
