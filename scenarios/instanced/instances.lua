local I=require('instanced')
local c
local ok,failure=pcall(function()
  stage.step('preparar nivel, salas y portal',function() c=I.dungeon({returns=1,release=1,cap=2}) end)
  stage.step('entrada al punto de inicio de una sala',function() c.enter(); assert(#c.ids()==1) end)
  stage.step('reconectar mantiene al jugador dentro',function()
    stage.disconnect(); stage.wait(3); stage.connect(); stage.assert_dimension(c.dimension)
  end)
  stage.step('salida al punto configurado',function()
    c.exit(); local p=stage.player(); assert(math.abs(p.x-0.5)<0.1 and math.abs(p.y-100)<0.1 and math.abs(p.z-0.5)<0.1)
  end)
  stage.step('morir permite volver a la misma instancia',function()
    local before=assert(c.ids()[1]); c.enter(); stage.command('kill @s')
    stage.wait_screen('DeathScreen',10); stage.wait(1.5); stage.click_widget('Respawn|Reaparecer'); stage.wait_no_screen(15)
    c.enter(); assert(#c.ids()==1 and c.ids()[1]==before); c.exit()
  end)
  stage.step('ticket y cuenta atrás liberan la instancia vacía',function()
    for _=1,150 do if #c.ids()==0 then return end; stage.wait(1) end
    error('la instancia no se liberó')
  end)
  stage.step('un administrador libera con el jugador dentro',function()
    c.enter(); stage.command('instanced instance release '..assert(c.ids()[1]))
    stage.expect_chat('Un administrador ha cerrado la instancia',10); I.wait_dimension('minecraft:overworld')
  end)
  stage.step('la tercera instancia por hora se rechaza',function()
    c.enter([[podrás entrar en una nueva dentro de \d\d:\d\d\.]])
    stage.assert_dimension('minecraft:overworld')
  end)
end)
if c then c.cleanup() end
if not ok then error(failure,0) end
