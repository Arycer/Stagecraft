local I,G=require('instanced'),require('gui')
local instanceId
local ok,failure=pcall(function()
  stage.step('jugar y consultar la instancia antes de cerrarla',function()
    stage.command('gamemode creative'); I.resetcap(); I.prepare_showcase(); I.enter_showcase(); stage.wait(2)
    G.admin(); G.tab(4); stage.click_text('^activa · 1 dentro')
    stage.wait_text('^Creada hace \\d+m \\d\\ds$')
    stage.wait_text('^Se liberará \\d+ min después de'); stage.wait_text('quedarse vacía y sin tickets')
    stage.wait_text('^'..stage.player().name..' · \\d+m \\d\\ds$'); stage.wait_text('^Ir a la instancia$')
    stage.close(); instanceId=I.active_id('demo:showcase')
    stage.command('instanced instance release '..instanceId); stage.expect_chat('Un administrador ha cerrado la instancia',10)
    I.wait_dimension('minecraft:overworld'); stage.wait(4)
  end)
  stage.step('jugadores: historial, eventos y límite por hora',function()
    G.admin(); G.tab(5)
    stage.set_field(G.label('Buscar jugador'),stage.player().name:sub(2)); stage.wait(1)
    stage.click_text('^'..stage.player().name..'$')
    stage.wait_text('^Instancias jugadas · [1-9]\\d*$')
    stage.wait_text([[^1 entrada\(s\) · \d+m \d\ds · (cerrada por admin|liberada por un admin)$]])
    stage.click_text('^\\d\\d/\\d\\d .*Sala de')
    stage.wait_text('^Instancia '..instanceId..'$')
    stage.wait_text('^'..stage.player().name..' entró$'); stage.wait_text('^'..stage.player().name..' salió · (cerrada por admin|liberada por un admin)$')
    stage.wait_text('^Instancia (creada|liberada)$'); stage.click_text('^← Volver$')
    stage.wait_text('^1 de \\d+ instancias nuevas en la última hora')
    stage.click_text('^Reiniciar límite$'); stage.wait_text('^0 de \\d+ instancias nuevas en la última hora')
  end)
end)
if not ok then pcall(G.dump) end
I.cleanup(); I.resetcap()
if not ok then error(failure,0) end
