local I,G=require('instanced'),require('gui')
local ns='place_'..stage.run_id
local function placed()
  stage.expect_chat('Colocado schematics/'..ns..'/room\\.schem · \\d+ bloques',30); stage.wait(0.5)
end
local ok,failure=pcall(function()
  stage.step('capturar sala y borrarla del mundo',function()
    stage.command('gamemode creative'); I.tp_to('minecraft:overworld',40,120,36); stage.fly(true)
    stage.command('fill 40 120 40 54 130 54 minecraft:air')
    stage.command('fill 42 120 42 46 122 46 minecraft:stone_bricks hollow')
    stage.command('setblock 40 120 40 instanced:capture{Offset:[I;2,0,2],Size:[I;5,3,5],Target:"schematics",Path:"'..ns..'/room.nbt"}')
    stage.command('instanced capture 40 120 40'); stage.expect_chat('Capturado schematics/'..ns..'/room\\.schem · 5×3×5',15)
    G.nbt('40 120 40','Path','"'..ns..'/room\\.schem"')
    stage.command('fill 42 120 42 46 122 46 minecraft:air'); G.block('42 120 42','minecraft:air')
  end)
  stage.step('Colocar elige fichero y confirma la sustitución',function()
    G.open('40 120 40'); stage.click_text('^Colocar…$'); stage.wait_text('^Colocar un schematic$')
    stage.click_text('^\\s+room\\.schem$'); stage.click_text('^Colocar$')
    stage.wait_text('Se vaciará la caja y se colocará')
    stage.click_text('^Colocar$'); placed()
    G.block('42 120 42','minecraft:stone_bricks'); G.block('44 121 44','minecraft:air'); G.block('40 120 40','instanced:capture')
  end)
  stage.step('editar, capturar y colocar conserva la edición',function()
    stage.close(); stage.command('setblock 44 121 44 minecraft:gold_block')
    stage.command('instanced capture 40 120 40'); stage.expect_chat('Reemplazado schematics/'..ns..'/room\\.schem · 5×3×5',15)
    stage.command('fill 42 120 42 46 122 46 minecraft:air')
    stage.command('instanced capture 40 120 40 place schematics '..ns..'/room.schem'); placed()
    G.block('44 121 44','minecraft:gold_block')
  end)
  stage.step('fichero inexistente rechazado',function()
    stage.command('instanced capture 40 120 40 place schematics '..ns..'/none.nbt')
    stage.expect_chat('No existe schematics/'..ns..'/none\\.nbt',10)
  end)
end)
if not ok then pcall(G.dump) end
I.cleanup(function() stage.command('execute in minecraft:overworld run fill 40 120 40 54 130 54 minecraft:air'); I.delete_namespace(ns) end)
if not ok then error(failure,0) end
